#!/usr/bin/env python3
"""Makes rtl/karabas/cpc_emu.sv from upstream/Amstrad.sv (the emu module of the fork).

cpc_emu = the machine and its MiSTer-side glue (loaders, SNA, tape, FDC, Plus) without the MiSTer
framework: no hps_io (its outputs are ports, cpc_core makes them from kg_mcu2), no pll (clk_sys is a
port), no Cyclone SDRAM (cpc_sram has the ports of sdram.v on the board SRAM), no DDR3, no ADC (the
tape input is a port). The picture leaves through the obs_* taps of amstrad_video_output (the colours
and syncs before the MiSTer video mixer); the board tops line-double it. KG_CLASSIC is defined:
classic CPC only (Plus model forced Off, no CPR, no SSM markers, no SNA save), see docs/PLAN.md Ф0.

Every replacement must match exactly once, so an upstream change that moves the code stops here.
Run from src/: python3 tools/make_cpc_emu.py  (then tools/sv2v.sh core).
"""
import sys

SRC = '../upstream/Amstrad.sv'
DST = 'rtl/karabas/cpc_emu.sv'

s = open(SRC).read()


def rep(old, new, count=1):
    global s
    n = s.count(old)
    if n != count:
        sys.exit(f'make_cpc_emu: {n} matches (want {count}) of:\n{old}')
    s = s.replace(old, new)


HEADER = '''// karabas: generated by src/tools/make_cpc_emu.py from upstream/Amstrad.sv (renaudguerin
// Amstrad_MiSTer v2026.11.07): edit the script, not this file. The emu module without the MiSTer
// framework, see the script for what changed.
`define KG_CLASSIC
'''

rep('module emu\n(\n\t`include "sys/emu_ports.vh"\n);\n', '''module cpc_emu
(
	input         clk_sys,       // 64 MHz
	input         locked,        // clocks stable (SRAM init)
	input         RESET,

	// hps_io outputs (cpc_core)
	input  [63:0] status,
	input   [1:0] buttons,
	input  [10:0] ps2_key,
	input  [24:0] ps2_mouse,
	input   [6:0] joy1_usb,
	input   [6:0] joy2_usb,
	input         ioctl_download,
	input   [7:0] ioctl_index,
	input         ioctl_wr,
	input  [24:0] ioctl_addr,
	input   [7:0] ioctl_dout,
	input  [31:0] ioctl_file_ext,
	output        ioctl_wait,
	input   [1:0] img_mounted,
	input  [63:0] img_size,
	input         img_readonly,
	output [31:0] sd_lba,
	output  [1:0] sd_rd,
	output  [1:0] sd_wr,
	input   [1:0] sd_ack,
	input   [8:0] sd_buff_addr,
	input   [7:0] sd_buff_dout,
	output  [7:0] sd_buff_din,
	input         sd_buff_wr,

	// the board SRAM (cpc_sram)
	output [20:0] MA,
	input  [15:0] MD_I,
	output [15:0] MD_O,
	output        MD_OE,
	output  [1:0] MWR_N,
	output  [1:0] MRD_N,

	// the picture at ce_pix (16 MHz), syncs and blanks high active
	output        vid_ce,
	output  [7:0] vid_r,
	output  [7:0] vid_g,
	output  [7:0] vid_b,
	output        vid_hs,
	output        vid_vs,
	output        vid_hbl,
	output        vid_vbl,

	output [15:0] AUDIO_L,
	output [15:0] AUDIO_R,

	input         tape_in,
	output        tape_out,
	output        led_user
);
''')
s = HEADER + s

rep('''assign ADC_BUS  = 'Z;
assign USER_OUT = '1;
assign {UART_RTS, UART_TXD, UART_DTR} = 0;
assign {SD_SCK, SD_MOSI, SD_CS} = 'Z;
assign DDRAM_RD = 0;   // the SSM event ring and the SNA save write only; see below

assign LED_USER  = mf2_en | ioctl_download | tape_led | tape_adc_act;
assign LED_DISK  = 0;
assign LED_POWER = 0;
assign BUTTONS   = 0;
assign VGA_SCALER= 0;
assign VGA_DISABLE = 0;
assign HDMI_FREEZE = 0;
assign HDMI_BLACKOUT = 0;
assign HDMI_BOB_DEINT = 0;
''', '''assign led_user = mf2_en | ioctl_download | tape_led; // karabas: the board ports
wire HDMI_FREEZE = 1'b0;
wire [11:0] HDMI_WIDTH = 12'd0, HDMI_HEIGHT = 12'd0;
wire OSD_STATUS = 1'b0;
wire [6:0] USER_IN = 7'h7F;
// karabas: no DDR3 (it carried only the SSM ring and the SNA save, both off in KG_CLASSIC)
wire DDRAM_BUSY = 1'b0;
wire [28:0] DDRAM_ADDR;
wire [63:0] DDRAM_DIN;
wire  [7:0] DDRAM_BE, DDRAM_BURSTCNT;
wire        DDRAM_WE, DDRAM_CLK;
wire CLK_VIDEO, CE_PIXEL, VGA_HS, VGA_VS, VGA_DE, VGA_F1;
wire [7:0] VGA_R, VGA_G, VGA_B;
wire [1:0] VGA_SL;
wire [12:0] VIDEO_ARX, VIDEO_ARY;
''')

# CONF_STR is kept as the reference of the status bits; no build_id.v
rep('`include "build_id.v"', '`define BUILD_ID "karabas" // karabas: no build_id.v (CONF_STR is unused)')

# clocks: clk_sys and locked are ports
rep('''wire clk_sys;
wire locked;
wire [15:0] status_menumask;''', '''wire [15:0] status_menumask;''')
rep('''pll pll
(
	.refclk(CLK_50M),
	.outclk_0(clk_sys),
	.locked(locked)
);
''', '')

rep('''reg ce_16;
always @(posedge clk_sys) begin
	reg [2:0] div = 0;
''', '''reg ce_16;
reg [2:0] div = 0; // karabas: out of the always block (sv2v re-inits a local initialised reg every clock)
always @(posedge clk_sys) begin
''')

# hps_io: its outputs are ports now
rep('''wire [31:0] sd_lba;
wire  [1:0] sd_rd;
wire  [1:0] sd_wr;
wire  [1:0] sd_ack;
wire  [8:0] sd_buff_addr;
wire  [7:0] sd_buff_dout;
wire  [7:0] sd_buff_din;
wire        sd_buff_wr;
wire  [1:0] img_mounted;
wire [63:0] img_size;
wire        img_readonly;

wire        ioctl_wr;
wire [24:0] ioctl_addr;
wire  [7:0] ioctl_dout;
wire        ioctl_download;
wire  [7:0] ioctl_index;
wire [31:0] ioctl_file_ext;
wire        ioctl_wait;
''', '')
rep('''wire [10:0] ps2_key;
wire [24:0] ps2_mouse;

wire  [1:0] buttons;
wire  [6:0] joy1_usb;
wire  [6:0] joy2_usb;
wire [63:0] status;

wire        forced_scandoubler;
wire [21:0] gamma_bus;
''', '''wire        forced_scandoubler = 1'b0;
wire [21:0] gamma_bus;
''')
i = s.index('hps_io #(.CONF_STR(CONF_STR), .VDNUM(2)) hps_io\n(')
j = s.index(');\n', i) + 3
s = s[:i] + '// karabas: no hps_io, its outputs are the ports of cpc_emu (cpc_core makes them)\n' + s[j:]

# KG_CLASSIC switches (as in src/measure/Amstrad.sv)
rep(" .plus_model(plus_model),\n .status_in(load_status_in),", "`ifdef KG_CLASSIC\n .plus_model(plus_model_loaded), // karabas: classic-only build, Plus off\n`else\n .plus_model(plus_model),\n`endif\n .status_in(load_status_in),")
rep("wire [1:0] plus_model;\n", "wire [1:0] plus_model;\n`ifdef KG_CLASSIC\nwire [1:0] plus_model_loaded;\nassign plus_model = 2'b00; // karabas: classic-only build\n`endif\n")
rep("wire        cpr_download = ioctl_download && (ioctl_index == 8);", "`ifdef KG_CLASSIC\nwire        cpr_download = 1'b0; // karabas: classic-only build\n`else\nwire        cpr_download = ioctl_download && (ioctl_index == 8);\n`endif")
rep("wire ssm_enable = status[37];", "`ifdef KG_CLASSIC\nwire ssm_enable = 1'b0; // karabas: classic-only build, no SSM markers\n`else\nwire ssm_enable = status[37];\n`endif")
rep("wire save_req = status[38] & ~old_save_osd;", "`ifdef KG_CLASSIC\nwire save_req = 1'b0; // karabas: classic-only build, no snapshot save\n`else\nwire save_req = status[38] & ~old_save_osd;\n`endif")

# XST fixes
rep('wire [12:0] mf2_store_addr;', 'reg  [12:0] mf2_store_addr; // karabas: wire assigned in always @(*) (XST rejects it)')
rep("    .CHG_Rxd(1'b1)", "    .CHG_Rxd() // karabas: an output, was tied to 1")

# memory: the board SRAM with the ports of sdram.v
rep('''sdram sdram
(
	.*,
''', '''cpc_sram sdram // karabas: the board SRAM, the ports of sdram.v
(
	.MA(MA), .MD_I(MD_I), .MD_O(MD_O), .MD_OE(MD_OE), .MWR_N(MWR_N), .MRD_N(MRD_N),
''')

# video: the obs_* taps leave the module
rep('''assign CLK_VIDEO = clk_sys;
''', '''assign CLK_VIDEO = clk_sys;
// karabas: the picture before the MiSTer mixer, for the line doubler of the board tops
assign vid_ce = obs_ce_pix;
assign vid_r = obs_r;
assign vid_g = obs_g;
assign vid_b = obs_b;
assign vid_hs = obs_hs;
assign vid_vs = obs_vs;
assign vid_hbl = obs_hbl;
assign vid_vbl = obs_vbl;
''')

# audio: no MiSTer mixer outputs
rep('''assign AUDIO_S   = 0;
assign AUDIO_MIX = status[8:7];
''', '''assign tape_out = tape_rec; // karabas: the tape output of the board
''')

# tape input: the TAPE_IN pin of the board instead of the ADC of MiSTer
rep('''wire tape_adc, tape_adc_act;
ltc2308_tape ltc2308_tape
(
	.clk(CLK_50M),
	.ADC_BUS(ADC_BUS),
	.dout(tape_adc),
	.active(tape_adc_act)
);
''', '''// karabas: the tape input of the board (synchronised in cpc_core)
wire tape_adc = tape_in;
''')

open(DST, 'w').write(s)
print(f'{DST}: {s.count(chr(10))} lines')
